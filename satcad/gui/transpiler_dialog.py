from pathlib import Path

from PySide6.QtCore import QRegularExpression, Qt
from PySide6.QtGui import QColor, QFont, QGuiApplication, QSyntaxHighlighter, QTextCharFormat
from PySide6.QtWidgets import (QDialog, QFileDialog, QHBoxLayout, QLabel, QListWidget, QListWidgetItem, QPlainTextEdit, QPushButton, QSplitter, QTabBar,
                               QVBoxLayout, QWidget)

from .. import parametric_transpiler as tp
from ..engine import DesignError
from ..paths import designs_dir

FIDELITY_MARK = {"native": "●", "evaluated": "◐", "unsupported": "○"}
FIDELITY_COLOR = {"native": "#7ad07a", "evaluated": "#e5c07b", "unsupported": "#e06c75"}
PY_KEYWORDS = ("import", "from", "def", "return", "if", "else", "elif", "for", "in", "while", "try", "except", "raise", "class", "None", "True", "False", "not", "and", "or",
               "is", "with", "as", "lambda", "pass", "break", "continue", "global")
VBA_KEYWORDS = ("Dim", "As", "Sub", "End", "Set", "If", "Then", "Else", "ElseIf", "For", "Next", "To", "Function", "Private", "Public", "ByVal", "Nothing", "True", "False",
                "Not", "And", "Or", "Long", "Double", "String", "Boolean", "Variant", "Object", "Call", "Option", "Explicit", "Const")


class ScriptHighlighter(QSyntaxHighlighter):
    """Colours comments, strings, numbers and keywords. One class for Python-style and VBA-style scripts."""

    def __init__(self, document, vba: bool = False):
        super().__init__(document)
        self.vba = vba
        self.rules = []

        def fmt(color, bold=False):
            f = QTextCharFormat()
            f.setForeground(QColor(color))
            if bold:
                f.setFontWeight(QFont.Bold)
            return f
        words = VBA_KEYWORDS if vba else PY_KEYWORDS
        flags = QRegularExpression.CaseInsensitiveOption if vba else QRegularExpression.NoPatternOption
        self.rules.append((QRegularExpression(r"\b(" + "|".join(words) + r")\b", flags), fmt("#c678dd", True)))
        self.rules.append((QRegularExpression(r"\b[0-9]+(\.[0-9]+)?\b"), fmt("#d19a66")))
        self.rules.append((QRegularExpression(r'"([^"\\]|\\.)*"' if not vba else r'"([^"]|"")*"'), fmt("#98c379")))
        if not vba:
            self.rules.append((QRegularExpression(r"'([^'\\]|\\.)*'"), fmt("#98c379")))
            self.rules.append((QRegularExpression(r"\b(f_[a-z_]+|register_expression|add_param|_guard|_boolean|_move|_xform)\b"), fmt("#61afef")))
        self.comment = (QRegularExpression(r"'.*$") if vba else QRegularExpression(r"#.*$"), fmt("#7f848e"))

    def highlightBlock(self, text: str) -> None:
        for rx, f in self.rules:
            it = rx.globalMatch(text)
            while it.hasNext():
                m = it.next()
                self.setFormat(m.capturedStart(), m.capturedLength(), f)
        it = self.comment[0].globalMatch(text)
        while it.hasNext():                                                         # a comment wins over anything it contains (checked last, so it paints over)
            m = it.next()
            start = m.capturedStart()
            if text[:start].count('"') % 2 == 0:
                self.setFormat(start, m.capturedLength(), self.comment[1])
                break


class TranspilerDialog(QDialog):
    def __init__(self, design, parent=None):
        super().__init__(parent)
        self.design = design
        self.setWindowTitle("Parametric Transpiler Studio: export the feature tree to another CAD program")
        self.resize(1280, 780)
        self.setModal(False)
        self.ir = None
        self.error = ""
        try:
            self.ir = tp.build_ir(design)
        except (DesignError, ValueError) as e:
            self.error = str(e)

        root = QVBoxLayout(self)
        intro = QLabel("A STEP file is a dumb solid: the history and the equations are lost. These scripts rebuild the satCAD model with native features and equations in "
                       "the CAD program you choose.")
        intro.setWordWrap(True)
        intro.setStyleSheet("color:#9aa2ad")
        root.addWidget(intro)
        split = QSplitter(Qt.Horizontal)
        root.addWidget(split, 1)

        left = QWidget()
        lv = QVBoxLayout(left)
        lv.setContentsMargins(0, 0, 0, 0)
        self.tabs = QTabBar()
        self.tabs.setExpanding(True)
        self.tabs.setDrawBase(False)
        for t in tp.TARGETS:
            self.tabs.addTab(tp.TARGET_LABEL[t])
        self.tabs.currentChanged.connect(self.refresh)
        lv.addWidget(self.tabs)
        self.coverage = QLabel()
        self.coverage.setWordWrap(True)
        lv.addWidget(self.coverage)
        lv.addWidget(QLabel("Global parameters (every variable becomes an equation in the target program)"))
        self.param_list = QListWidget()
        lv.addWidget(self.param_list, 1)
        lv.addWidget(QLabel("Feature tree (untick a feature to leave it out of the script)   ● native   ◐ some numbers evaluated   ○ unsupported"))
        self.node_list = QListWidget()
        self.node_list.itemChanged.connect(lambda _: self.refresh())
        lv.addWidget(self.node_list, 3)
        split.addWidget(left)

        right = QWidget()
        rv = QVBoxLayout(right)
        rv.setContentsMargins(0, 0, 0, 0)
        self.code = QPlainTextEdit()
        self.code.setReadOnly(True)
        self.code.setLineWrapMode(QPlainTextEdit.NoWrap)
        mono = QFont("Menlo")
        mono.setStyleHint(QFont.Monospace)
        mono.setPointSize(11)
        self.code.setFont(mono)
        self.highlighter = ScriptHighlighter(self.code.document())
        rv.addWidget(self.code, 1)
        buttons = QHBoxLayout()
        self.copy_button = QPushButton("Copy to Clipboard")
        self.save_button = QPushButton("Save Native Script...")
        self.bundle_button = QPushButton("Export Bundle (.STEP + All 4 Parametric Scripts)...")
        self.copy_button.clicked.connect(self.copy)
        self.save_button.clicked.connect(self.save_script)
        self.bundle_button.clicked.connect(self.export_bundle)
        for b in (self.copy_button, self.save_button, self.bundle_button):
            buttons.addWidget(b)
        rv.addLayout(buttons)
        self.status = QLabel("")
        self.status.setStyleSheet("color:#9aa2ad")
        rv.addWidget(self.status)
        split.addWidget(right)
        split.setSizes([430, 850])

        self._fill_lists()
        self.refresh()

    # ---- content -------------------------------------------------------------------------------------------------------------------------
    def _fill_lists(self) -> None:
        self.param_list.clear()
        self.node_list.blockSignals(True)
        self.node_list.clear()
        if self.ir is None:
            return
        for p in self.ir.params:
            unit = f" {p.unit}" if p.unit else ""
            text = f"{p.name} = {p.expr.src}   ->  {p.value:g}{unit}" if p.expr.is_formula else f"{p.name} = {p.value:g}{unit}"
            item = QListWidgetItem(text)
            item.setFlags(Qt.ItemIsEnabled)
            self.param_list.addItem(item)
        for n in self.ir.nodes:
            if n.kind in ("CSYS_Datum",):
                continue
            item = QListWidgetItem(f"{FIDELITY_MARK[n.fidelity]}  {n.id}   [{n.kind}]")
            item.setForeground(QColor(FIDELITY_COLOR[n.fidelity]))
            item.setFlags(Qt.ItemIsEnabled | Qt.ItemIsUserCheckable)
            item.setCheckState(Qt.Checked)
            item.setData(Qt.UserRole, id(n))
            item.setToolTip("; ".join(n.notes) or n.fidelity)
            self.node_list.addItem(item)
        self.node_list.blockSignals(False)

    def target(self) -> str:
        return tp.TARGETS[self.tabs.currentIndex()]

    def selected_ir(self):
        """The IR with the unticked features removed."""
        if self.ir is None:
            return None
        keep = set()
        for i in range(self.node_list.count()):
            it = self.node_list.item(i)
            if it.checkState() == Qt.Checked:
                keep.add(it.data(Qt.UserRole))
        nodes = [n for n in self.ir.nodes if n.kind == "CSYS_Datum" or id(n) in keep]
        return tp.IR(self.ir.name, self.ir.params, nodes, self.ir.warnings, self.ir.generated)

    def script(self) -> str:
        ir = self.selected_ir()
        if ir is None:
            return ""
        return tp.GENERATORS[self.target()](ir)

    def refresh(self, *_args) -> None:
        if self.ir is None:
            self.code.setPlainText(f"# Nothing to show: {self.error}")
            self.coverage.setText(self.error)
            return
        vba = self.target() == "solidworks"
        if getattr(self.highlighter, "vba", None) != vba:                              # a new highlighter per language
            self.highlighter.setDocument(None)
            self.highlighter = ScriptHighlighter(self.code.document(), vba=vba)
        self.code.setPlainText(self.script())
        cov = self.selected_ir().coverage()
        self.coverage.setText(f"{len(self.ir.params)} parameters; {sum(cov.values())} features: {cov['native']} native, {cov['evaluated']} with evaluated numbers, "
                              f"{cov['unsupported']} unsupported (use the STEP file for those).")
        self.status.setText("The API calls in this script have not been run against the real program: read it and try it on a copy first.")

    # ---- actions -------------------------------------------------------------------------------------------------------------------------
    def copy(self) -> None:
        QGuiApplication.clipboard().setText(self.script())
        self.status.setText("Copied the script to the clipboard.")

    def save_script(self, path: str | None = None) -> bool:
        target = self.target()
        if not path:
            path, _ = QFileDialog.getSaveFileName(self, "Save native script", str(designs_dir() / f"{self.design.name}_{tp.TARGET_FILE[target]}"), "Scripts (*.py *.vba *.FCMacro)")
        if not path:
            return False
        try:
            Path(path).write_text(self.script(), encoding="utf-8")
        except OSError as e:
            self.status.setText(f"Couldn't save: {e}")
            return False
        self.status.setText(f"Saved {path}")
        return True

    def export_bundle(self, folder: str | None = None) -> bool:
        if not folder:
            folder = QFileDialog.getExistingDirectory(self, "Export bundle to folder", str(designs_dir()))
        if not folder:
            return False
        try:
            paths = tp.export_bundle(self.design, folder)
        except (DesignError, OSError, ValueError) as e:
            self.status.setText(f"Export failed: {e}")
            return False
        self.status.setText(f"Exported the STEP file and 4 scripts to {folder} (also {paths['zip'].name})")
        return True
